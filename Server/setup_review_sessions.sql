-- WS4 session state: one row per submission, following the list in Team1Week7E5Docs.md.
-- Run once in the Supabase SQL editor.
create table if not exists public."Review_Sessions" (
  id                bigint generated by default as identity primary key,  -- session ID
  submission_id     bigint not null unique references public."Submission"(id) on delete cascade,
  user_id           bigint not null references public."USER"(id),
  assignment_id     bigint not null references public."ASSIGNMENT"(id),
  attempt_number    integer not null default 1,
  route             text not null,                  -- PASS / FAIL / MANUAL_REVIEW (router.py)
  reason_code       text,                           -- e.g. WRONG_OUTPUT; null on PASS
  path              text not null,                  -- A / B / instructor
  status            text not null default 'active'
                    check (status in ('active', 'retry', 'escalated', 'complete')),
  current_question  integer not null default 0,     -- index into questions
  retry_number      integer not null default 0,
  questions         jsonb not null default '[]',    -- previous questions, in order
  scores            jsonb not null default '[]',    -- {question, answer, score} per answer
  evaluator_version text,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);
-- Tokens used already live in AI_Conversations."Tokens_used" (same submission id).

create or replace function public.touch_updated_at() returns trigger as $$
begin new.updated_at = now(); return new; end; $$ language plpgsql;

create or replace trigger review_sessions_touch before update on public."Review_Sessions"
  for each row execute function public.touch_updated_at();

-- The Python server uses the secret key, which bypasses RLS.
-- RLS on (with no policies) stops the browser's publishable key from touching this table.
alter table public."Review_Sessions" enable row level security;
